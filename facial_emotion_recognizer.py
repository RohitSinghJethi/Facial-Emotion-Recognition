import matplotlib.pyplot as plt
from PIL import Image

image_extensions = ['.jpg', '.jpeg', '.png', '.bmp']

images = [
    f for f in Path('/content/fer_data').rglob('*')
    if f.is_file() and f.suffix.lower() in image_extensions
]

print("Total images found:", len(images))

if images:
    img = Image.open(images[0])
    plt.imshow(img, cmap='gray')
    plt.title(images[0].parent.name)
    plt.axis('off')
    plt.show()

import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers

DATA_DIR = '/content/fer_data/images'

IMG_SIZE = (48, 48)
BATCH_SIZE = 32

train_ds = keras.utils.image_dataset_from_directory(
    f'{DATA_DIR}/train',
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    color_mode='grayscale',
    label_mode='int',
    shuffle=True,
    seed=42
)

val_ds = keras.utils.image_dataset_from_directory(
    f'{DATA_DIR}/validation',
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    color_mode='grayscale',
    label_mode='int',
    shuffle=False
)

class_names = train_ds.class_names

print("Expression classes:", class_names)
print("Number of classes:", len(class_names))

train_ds = train_ds.map(
    lambda x, y: (x / 255.0, y),
    num_parallel_calls=tf.data.AUTOTUNE
)

val_ds = val_ds.map(
    lambda x, y: (x / 255.0, y),
    num_parallel_calls=tf.data.AUTOTUNE
)

train_ds = train_ds.prefetch(tf.data.AUTOTUNE)
val_ds = val_ds.prefetch(tf.data.AUTOTUNE)

plt.figure(figsize=(12, 8))

for images, labels in train_ds.take(1):
    for i in range(12):
        ax = plt.subplot(3, 4, i + 1)

        plt.imshow(images[i].numpy().squeeze(), cmap='gray')
        plt.title(class_names[int(labels[i])])
        plt.axis('off')

plt.tight_layout()
plt.show()

model = keras.Sequential([
    layers.Input(shape=(48, 48, 1)),

    layers.Conv2D(32, (3, 3), padding='same', activation='relu'),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), padding='same', activation='relu'),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(128, (3, 3), padding='same', activation='relu'),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(256, (3, 3), padding='same', activation='relu'),
    layers.MaxPooling2D((2, 2)),

    layers.GlobalAveragePooling2D(),

    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5),

    layers.Dense(len(class_names), activation='softmax')
])

model.compile(
    optimizer=keras.optimizers.Adam(learning_rate=0.001),
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

model.summary()

callbacks = [
    keras.callbacks.EarlyStopping(
        monitor='val_loss',
        patience=4,
        restore_best_weights=True
    ),

    keras.callbacks.ModelCheckpoint(
        '/content/best_fer_model.keras',
        monitor='val_accuracy',
        save_best_only=True
    )
]

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=20,
    callbacks=callbacks
)


plt.figure(figsize=(10, 5))

plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')

plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.title('Facial Expression Recognition Accuracy')
plt.legend()
plt.grid(True)
plt.show()

